-- dim_players — one row per player VERSION (SCD Type 2).
--
-- Players change clubs (transfers) and occasionally recorded position, so we
-- keep history: a fact row references the player as they were on the match date.
-- The current version has is_current = true and valid_to IS NULL.
-- `understat_player_id` is the durable business key shared across versions.

CREATE TABLE IF NOT EXISTS gold.dim_players (
    player_key           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    understat_player_id  BIGINT      NOT NULL,          -- durable business key
    player_name          TEXT        NOT NULL,
    position             VARCHAR(10),
    current_team_key     BIGINT      REFERENCES gold.dim_teams (team_key),
    valid_from           DATE        NOT NULL,
    valid_to             DATE,                           -- NULL = still current
    is_current           BOOLEAN     NOT NULL DEFAULT true,
    loaded_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_dim_players_validity CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- Exactly one current version per player.
CREATE UNIQUE INDEX IF NOT EXISTS uq_dim_players_current
    ON gold.dim_players (understat_player_id) WHERE is_current;

-- Lookup of the historical version valid on a given date.
CREATE INDEX IF NOT EXISTS ix_dim_players_bk ON gold.dim_players (understat_player_id);

