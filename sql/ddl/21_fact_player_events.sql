-- fact_player_events — GRAIN: one row per player per match.
--
-- Shot/xG-centric per-player stats from Understat `getMatchData` rosters.
-- `player_key` points at the SCD Type 2 dim_players version valid on the match
-- date. `match_key` is NULL until the match is matched into fact_matches, but the
-- Understat natural keys are always present for idempotent upserts.
--
-- Omitted on purpose: total passes, tackles, possession — FBref-only and blocked.

CREATE TABLE IF NOT EXISTS gold.fact_player_events (
    player_event_key     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Natural key parts (idempotent upsert key)
    understat_match_id   INTEGER     NOT NULL,
    understat_player_id  BIGINT      NOT NULL,

    -- Dimension foreign keys
    match_key            BIGINT      REFERENCES gold.fact_matches (match_key),
    player_key           BIGINT      NOT NULL REFERENCES gold.dim_players (player_key),
    team_key             BIGINT      NOT NULL REFERENCES gold.dim_teams (team_key),

    -- Degenerate dimensions
    match_date           DATE,
    position             VARCHAR(10),

    -- Measures (Understat rosters)
    minutes_played       SMALLINT,
    goals                SMALLINT,
    own_goals            SMALLINT,
    assists              SMALLINT,
    shots                SMALLINT,
    key_passes           SMALLINT,
    xg                   NUMERIC(8,4),
    xa                   NUMERIC(8,4),
    xg_chain             NUMERIC(8,4),
    xg_buildup           NUMERIC(8,4),
    yellow_cards         SMALLINT,
    red_cards            SMALLINT,

    loaded_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_fact_player_events UNIQUE (understat_match_id, understat_player_id),
    CONSTRAINT ck_fpe_nonneg CHECK (
        (minutes_played IS NULL OR minutes_played >= 0)
        AND (goals IS NULL OR goals >= 0)
        AND (shots IS NULL OR shots >= 0)
    )
);

CREATE INDEX IF NOT EXISTS ix_fpe_match  ON gold.fact_player_events (match_key);
CREATE INDEX IF NOT EXISTS ix_fpe_player ON gold.fact_player_events (player_key);
CREATE INDEX IF NOT EXISTS ix_fpe_team   ON gold.fact_player_events (team_key);
