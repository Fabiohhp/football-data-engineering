-- dim_stadiums — one row per home ground, sourced from Football-Data.
--
-- Populated from `/competitions/{code}/teams`, whose `venue` field names each
-- club's ground. That endpoint is the only venue source this pipeline has:
-- Understat exposes none, and FBref (which also carries city and capacity) is
-- Cloudflare-blocked from our environment.
--
-- Consequences of that single source, all deliberate:
--
--   * `city` and `capacity` are never populated. Football-Data has no capacity
--     field at all, and its `address` is free-form and country-specific
--     ("75 Drayton Park London N5 1BU") — splitting a city out of it would be a
--     heuristic that quietly produces wrong values. The raw address is kept
--     instead, and the two columns stay as the slot a future source fills.
--   * The grain is the ground, not the club-season. Clubs that share a stadium
--     (Inter and Milan at San Siro) resolve to one row.
--   * SCD Type 1. A club that moves grounds re-points `fact_matches.stadium_key`
--     from the next load on; historical matches are not restated, because the
--     source only ever reports the *current* venue.
--
-- The 'Unknown' member (key 0) remains, and is what a match whose home club is
-- absent from the roster payload still points at.

CREATE TABLE IF NOT EXISTS gold.dim_stadiums (
    stadium_key    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stadium_name   TEXT        NOT NULL,
    address        TEXT,                 -- free-form, as the source reports it
    city           TEXT,                 -- no source; see header
    country        TEXT,
    capacity       INTEGER,              -- no source; see header
    loaded_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_stadiums_name UNIQUE (stadium_name)
);

-- `address` post-dates the original placeholder table, and the DDL above is
-- CREATE ... IF NOT EXISTS, so an existing warehouse would never gain it.
ALTER TABLE gold.dim_stadiums ADD COLUMN IF NOT EXISTS address TEXT;

-- 'Unknown' member (key 0) so facts can always carry a non-null stadium
-- reference, including matches whose home club has no venue on record.
INSERT INTO gold.dim_stadiums (stadium_key, stadium_name)
VALUES (0, 'Unknown')
ON CONFLICT (stadium_key) DO NOTHING;
