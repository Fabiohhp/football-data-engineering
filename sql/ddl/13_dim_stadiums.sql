-- dim_stadiums — PLACEHOLDER dimension.
--
-- Neither live source exposes venue data: Football-Data's free tier omits it,
-- and FBref (which has it) is Cloudflare-blocked from our environment
-- (see the source-availability findings). The table and the fact_matches FK are
-- kept so the star-schema shape stays stable for Parts 2/3; only the 'Unknown'
-- member is populated until a venue source is added.

CREATE TABLE IF NOT EXISTS gold.dim_stadiums (
    stadium_key    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stadium_name   TEXT        NOT NULL,
    city           TEXT,
    country        TEXT,
    capacity       INTEGER,
    loaded_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_stadiums_name UNIQUE (stadium_name)
);

-- 'Unknown' member (key 0) — the only populated row for now.
INSERT INTO gold.dim_stadiums (stadium_key, stadium_name)
VALUES (0, 'Unknown')
ON CONFLICT (stadium_key) DO NOTHING;
