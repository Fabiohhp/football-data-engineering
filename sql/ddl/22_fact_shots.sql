-- fact_shots — GRAIN: one row per shot (Understat `getMatchData` shots).
--
-- Beyond the original CLAUDE.md fact list, added deliberately: per-shot xG with
-- pitch location is the single most valuable asset for the downstream xG / ML
-- subproject (Part 3), and it is cheap to model now while the data already lands
-- in Bronze. `x`/`y` are Understat's normalized pitch coordinates in [0, 1].

CREATE TABLE IF NOT EXISTS gold.fact_shots (
    shot_key            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    understat_shot_id   BIGINT      NOT NULL,          -- idempotent upsert key
    understat_match_id  INTEGER     NOT NULL,

    -- Dimension foreign keys
    match_key           BIGINT      REFERENCES gold.fact_matches (match_key),
    player_key          BIGINT      NOT NULL REFERENCES gold.dim_players (player_key),
    team_key            BIGINT      NOT NULL REFERENCES gold.dim_teams (team_key),
    assist_player_key   BIGINT      REFERENCES gold.dim_players (player_key),

    -- Measures / attributes (Understat shots)
    minute              SMALLINT,
    is_home             BOOLEAN,
    x                   NUMERIC(6,4),          -- normalized pitch coords, [0, 1]
    y                   NUMERIC(6,4),
    xg                  NUMERIC(7,4),
    result              VARCHAR(20),           -- Goal | SavedShot | MissedShots | BlockedShot | ...
    situation           VARCHAR(20),           -- OpenPlay | FromCorner | SetPiece | Penalty | ...
    shot_type           VARCHAR(20),           -- RightFoot | LeftFoot | Head | OtherBodyPart

    loaded_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_fact_shots UNIQUE (understat_shot_id),
    CONSTRAINT ck_fact_shots_xg CHECK (xg IS NULL OR (xg >= 0 AND xg <= 1))
);

CREATE INDEX IF NOT EXISTS ix_fact_shots_match  ON gold.fact_shots (match_key);
CREATE INDEX IF NOT EXISTS ix_fact_shots_player ON gold.fact_shots (player_key);
CREATE INDEX IF NOT EXISTS ix_fact_shots_team   ON gold.fact_shots (team_key);
