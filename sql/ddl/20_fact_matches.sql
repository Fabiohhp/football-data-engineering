-- fact_matches — GRAIN: one row per match.
--
-- Results/fixtures come from Football-Data; expected-goals measures from
-- Understat, matched on team + date in the Silver layer. Either source id may be
-- NULL when a match exists in only one source, but at least one is always
-- present (see ck_fact_matches_source).
--
-- Coverage note (documented, not silent): xG columns are NULL for competitions
-- Understat does not cover (Champions League, cups, non-big-5 leagues). Score
-- columns are NULL for matches not yet finished (see `status`).
--
-- Omitted on purpose: possession, total passes/tackles are FBref-only and FBref
-- is blocked, so we do NOT ship all-null columns for them (see README).

CREATE TABLE IF NOT EXISTS gold.fact_matches (
    match_key               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Source natural keys (idempotent upserts / cross-source matching)
    football_data_match_id  INTEGER,
    understat_match_id      INTEGER,

    -- Degenerate dimensions
    competition_code        VARCHAR(10),
    competition_name        TEXT,
    season                  VARCHAR(9),          -- e.g. '2025' or '2025/26'
    matchday                SMALLINT,
    match_utc               TIMESTAMPTZ,
    match_date              DATE        NOT NULL,
    status                  VARCHAR(20) NOT NULL,

    -- Dimension foreign keys (default 0 = 'Unknown' member => never silently null)
    home_team_key           BIGINT      NOT NULL REFERENCES gold.dim_teams (team_key),
    away_team_key           BIGINT      NOT NULL REFERENCES gold.dim_teams (team_key),
    referee_key             BIGINT      NOT NULL DEFAULT 0 REFERENCES gold.dim_referees (referee_key),
    stadium_key             BIGINT      NOT NULL DEFAULT 0 REFERENCES gold.dim_stadiums (stadium_key),

    -- Result measures (Football-Data)
    home_goals              SMALLINT,
    away_goals              SMALLINT,
    home_goals_ht           SMALLINT,
    away_goals_ht           SMALLINT,
    result                  VARCHAR(10),         -- HOME_TEAM | AWAY_TEAM | DRAW

    -- Expected-goals measures (Understat)
    home_xg                 NUMERIC(8,4),
    away_xg                 NUMERIC(8,4),
    home_npxg               NUMERIC(8,4),
    away_npxg               NUMERIC(8,4),
    home_ppda               NUMERIC(8,4),
    away_ppda               NUMERIC(8,4),
    home_deep               SMALLINT,
    away_deep               SMALLINT,
    home_xpts               NUMERIC(6,4),
    away_xpts               NUMERIC(6,4),

    loaded_at               TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_fact_matches_source
        CHECK (football_data_match_id IS NOT NULL OR understat_match_id IS NOT NULL),
    CONSTRAINT ck_fact_matches_result
        CHECK (result IS NULL OR result IN ('HOME_TEAM', 'AWAY_TEAM', 'DRAW')),
    CONSTRAINT ck_fact_matches_goals
        CHECK ((home_goals IS NULL OR home_goals >= 0)
           AND (away_goals IS NULL OR away_goals >= 0)),
    CONSTRAINT ck_fact_matches_teams_differ
        CHECK (home_team_key <> away_team_key)
);

-- Idempotency: at most one fact row per source match id.
CREATE UNIQUE INDEX IF NOT EXISTS uq_fact_matches_fd
    ON gold.fact_matches (football_data_match_id) WHERE football_data_match_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_fact_matches_us
    ON gold.fact_matches (understat_match_id) WHERE understat_match_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_fact_matches_date ON gold.fact_matches (match_date);
CREATE INDEX IF NOT EXISTS ix_fact_matches_comp ON gold.fact_matches (competition_code);
CREATE INDEX IF NOT EXISTS ix_fact_matches_home ON gold.fact_matches (home_team_key);
CREATE INDEX IF NOT EXISTS ix_fact_matches_away ON gold.fact_matches (away_team_key);
