-- dim_teams — one row per club, conformed across sources.
--
-- SCD Type 1: a club's name/crest/abbreviation are effectively stable, and its
-- match participation lives in the fact tables, so no history is tracked here.
-- `canonical_name` is the cross-source join key produced by
-- src.common.team_mapping.normalize_team_name — Football-Data ("Manchester
-- United FC") and Understat ("Man Utd") spell clubs differently and both resolve
-- to it. The two source ids are kept for lineage/lookup.

CREATE TABLE IF NOT EXISTS gold.dim_teams (
    team_key          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name    TEXT        NOT NULL,
    short_name        TEXT,
    tla               VARCHAR(5),          -- three-letter abbreviation (Football-Data)
    crest_url         TEXT,
    football_data_id  INTEGER,             -- source natural key (nullable)
    understat_id      INTEGER,             -- source natural key (nullable)
    loaded_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_teams_canonical UNIQUE (canonical_name)
);

CREATE INDEX IF NOT EXISTS ix_dim_teams_fd ON gold.dim_teams (football_data_id);
CREATE INDEX IF NOT EXISTS ix_dim_teams_us ON gold.dim_teams (understat_id);

-- 'Unknown' member (key 0) so facts can always carry a non-null team reference.
INSERT INTO gold.dim_teams (team_key, canonical_name)
VALUES (0, 'Unknown')
ON CONFLICT (team_key) DO NOTHING;
