-- dim_referees — one row per match official (Football-Data match.referees).
--
-- SCD Type 1: only identity and nationality are stored, which are stable.

CREATE TABLE IF NOT EXISTS gold.dim_referees (
    referee_key       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    football_data_id  INTEGER,                 -- source natural key
    referee_name      TEXT        NOT NULL,
    nationality       TEXT,
    loaded_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_referees_fd UNIQUE (football_data_id)
);

-- 'Unknown' member (key 0) — many matches have no referee assigned in the feed.
INSERT INTO gold.dim_referees (referee_key, football_data_id, referee_name)
VALUES (0, NULL, 'Unknown')
ON CONFLICT (referee_key) DO NOTHING;
